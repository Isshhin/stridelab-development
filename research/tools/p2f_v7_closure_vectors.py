#!/usr/bin/env python3
"""Generate and verify deterministic, test-only P2-F v7 closure vectors."""
from hashlib import sha256
from pathlib import Path

OUT = Path(__file__).parents[2] / "docs/research/phase2/p2-f-custody-authority-v7-closure-test-vectors-2026-11-07.md"
Z = bytes(32)

def u(n):
    if n < 24: return bytes([n])
    if n < 256: return b"\x18" + bytes([n])
    if n < 65536: return b"\x19" + n.to_bytes(2, "big")
    return b"\x1a" + n.to_bytes(4, "big")

def b(v): return (bytes([0x40 + len(v)]) if len(v) < 24 else b"\x58" + bytes([len(v)])) + v
def a(v): return bytes([0x80 + len(v)]) + b"".join(v)
def m(v): return bytes([0xa0 + len(v)]) + b"".join(u(k) + x for k, x in v)
def digest(domain, raw): return sha256(domain.encode() + b"\0" + raw).hexdigest()
def obj(items): return m([(k, b(v) if isinstance(v, bytes) else u(v)) for k, v in items])

ids = {i: bytes([i]) * 32 for i in range(1, 40)}
policy_old = obj([(0, 1), (1, ids[1]), (2, 7), (3, ids[2]), (4, ids[3]), (5, 3), (6, ids[4]), (7, ids[5]), (8, 1), (9, 1), (10, 1)])
policy_new = obj([(0, 1), (1, ids[1]), (2, 8), (3, ids[6]), (4, ids[7]), (5, 3), (6, ids[4]), (7, ids[5]), (8, 1), (9, 1), (10, 1)])
policy_old_d = digest("StrideLab/P2F/v1/policy", policy_old)
policy_new_d = digest("StrideLab/P2F/v1/policy", policy_new)

payloads = {
    1: obj([(0, ids[8]), (1, ids[9]), (2, ids[10]), (3, 12)]),
    16: obj([(0, ids[11]), (1, ids[12]), (2, ids[13])]),
    17: obj([(0, ids[14]), (1, ids[15]), (2, 4096), (3, ids[16]), (4, 1), (5, ids[17])]),
    18: obj([(0, ids[14]), (1, ids[17]), (2, ids[18])]),
    22: obj([(0, ids[19]), (1, 1)]),
    5: obj([(0, bytes.fromhex(policy_old_d)), (1, bytes.fromhex(policy_new_d)), (2, 7), (3, 42)]),
}

def request(event, ns, payload):
    return m([(0, u(1)), (1, u(event)), (2, b(ids[20])), (3, b(ids[1])), (4, b(ns)), (5, payload)])

def envelope(event, ns, payload, seq):
    req = request(event, ns, payload)
    raw = m([(0, u(1)), (1, u(event)), (2, b(ids[1])), (3, u(8)), (4, b(ids[2])),
             (5, u(seq)), (6, b(ids[3])), (7, b(ns)), (8, u(seq if ns == Z else 0)),
             (9, u(seq if ns != Z else 0)), (10, b(ids[4])), (11, b(Z)), (12, b(Z)),
             (13, b(ids[20])), (14, b(bytes.fromhex(digest("StrideLab/P2F/v1/request", req)))), (15, payload)])
    return req, raw

rows = []
for event, ns, seq in [(1, Z, 1), (16, ids[21], 1), (17, ids[21], 2), (18, ids[21], 3), (22, ids[21], 4), (5, Z, 5)]:
    req, ev = envelope(event, ns, payloads[event], seq)
    cert = m([(0, u(1)), (1, b(ids[1])), (2, u(8)), (3, b(bytes.fromhex(policy_new_d))),
              (4, b(ids[22])), (5, b(bytes.fromhex(digest("StrideLab/P2F/v1/event", ev)))),
              (6, b(Z)), (7, b(ids[3])), (8, b(ns)), (9, u(seq)), (10, u(0 if ns == Z else seq)),
              (11, u(0 if ns == Z else 1)), (12, b(ids[4])), (13, b(Z)), (14, u(event)), (15, u(1))])
    rows.append((event, req, ev, cert))

lines = ["# P2-F v7 Closure Canonical Test Vectors", "", "Generated by `research/tools/p2f_v7_closure_vectors.py`; all values are deterministic TEST FIXTURES ONLY.", "", f"Policy old bytes/digest: `{policy_old.hex()}` / `{policy_old_d}`", f"Policy new bytes/digest: `{policy_new.hex()}` / `{policy_new_d}`", "", "| Event | Request bytes/digest | Full event bytes/digest | Certificate body bytes/digest |", "|---:|---|---|---|"]
for event, req, ev, cert in rows:
    lines.append(f"| {event} | `{req.hex()}` / `{digest('StrideLab/P2F/v1/request', req)}` | `{ev.hex()}` / `{digest('StrideLab/P2F/v1/event', ev)}` | `{cert.hex()}` / `{digest('StrideLab/P2F/v1/cert', cert)}` |")
lines += ["", "## AuthorityFinalityProof example", "`{0: certificate_body, 1: [{0: policy_digest, 1: [[0, sig64], [1, sig64], [2, sig64]]}]}`; POLICY_BRIDGE uses two ApprovalSets over the identical body, old and new policy digests. Signatures are TEST KEYS ONLY.", "", "## Rejection fixtures", "Duplicate key, unknown key, unknown enum, non-minimal integer, indefinite map/array, tag, float, null, prohibited text, stale coordinator epoch, stale gateway epoch, duplicate SEND_STARTED release, bad policy epoch, and bad control-head binding are all rejected."]
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
for event, req, ev, cert in rows:
    assert bytes.fromhex(digest("StrideLab/P2F/v1/request", req))
    assert bytes.fromhex(digest("StrideLab/P2F/v1/event", ev))
    assert bytes.fromhex(digest("StrideLab/P2F/v1/cert", cert))
print(f"wrote {OUT} ({len(rows)} complete vectors); self-check passed")
